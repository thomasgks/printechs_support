#!/usr/bin/env node
/**
 * After `vite build`, copy hashed JS/CSS URLs from public/portal/index.html into a Jinja
 * include so embedded portal (portal_base.html) loads the same bundle as standalone index.html.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../..");
const builtHtml = path.join(root, "printechs_support/public/portal/index.html");
const outFile = path.join(root, "printechs_support/templates/includes/portal_react_bundle.html");

const html = fs.readFileSync(builtHtml, "utf8");
const scriptMatch = html.match(/<script[^>]+src="([^"]+)"/);
const linkMatch = html.match(/<link[^>]+href="([^"]+\.css)"/);
if (!scriptMatch || !linkMatch) {
	console.error("sync-portal-bundle-include: could not parse script/link from", builtHtml);
	process.exit(1);
}
const fragment = `{# Auto-generated by portal/scripts/sync-portal-bundle-include.cjs — do not edit by hand. #}
<link rel="stylesheet" crossorigin href="${linkMatch[1]}" />
<script type="module" crossorigin src="${scriptMatch[1]}"></script>
`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, fragment);
console.log("Wrote", outFile);
